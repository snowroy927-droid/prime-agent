const dirs: string[] = [];
afterEach(() => {
	for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true });
});

const ofType = <T extends EngineEvent["type"]>(events: EngineEvent[], type: T) =>
	events.filter((event): event is Extract<EngineEvent, { type: T }> => event.type === type);

async function runDemo(speed = 1): Promise<{ events: EngineEvent[]; symbols: Map<string, string> }> {
	const dir = mkdtempSync(join(tmpdir(), "demo-"));
	dirs.push(dir);
	const base = new ManualClock(Date.UTC(2026, 9, 15, 12, 0));
	const clock: Clock = speed === 1 ? base : new ScaledClock(base, speed);
	const driver = new ReplayDriver(buildDemoSession(7), clock);
	const bus = new EngineBus();
	const events: EngineEvent[] = [];
	bus.on((event) => events.push(event));
	const settings = new SettingsStore(join(dir, "settings.json"), {});
	const history = new LaunchHistory(null, clock);
	const budget = new RpcBudget(1_000, clock);
	let core: TradingCore | null = null;
	const executor = new PaperExecutor({
		mode: "demo",
		chain: driver.chain,
		globals: () => {
			if (!core) throw new Error("core not ready");
			return core.globals();
		},
		clock,
		settings: () => settings.get(),
	});
	core = new TradingCore({
		mode: "demo",
		synthetic: driver.synthetic,
		feed: driver.feed,
		chain: driver.chain,
		executor,
		ledger: new Ledger(join(dir, "ledger.jsonl")),
		history,
		scout: new Scout({ chain: driver.chain, budget, history, clock, settings: () => settings.get() }),
		risk: new RiskGuard({
			clock,
			limits: () => pumpLimits(settings.get()),
			copy: PUMP_RISK_COPY,
			tzOffsetMin: () => 0,
		}),
		budget,
		clock,
		bus,
		settings,
		publicRpcFallback: false,
		tzOffsetMin: () => 0,
	});
	await core.start();
	for (let second = 0; second < 205; second++) await base.advance(1_000 / speed);
	await core.stop();
	const symbols = new Map(ofType(events, "launch").map((event) => [event.launch.mint, event.launch.symbol]));
	return { events, symbols };
}

const fixtures = join(dirname(fileURLToPath(import.meta.url)), "..", "fixtures");

describe("synthetic demo session", () => {
	it("matches the checked-in fixtures that npm run make-demo writes", () => {
		expect(readFileSync(join(fixtures, "demo-session.jsonl"), "utf8")).toBe(formatRecording(buildDemoSession(7)));
		expect(readFileSync(join(fixtures, "kraken-demo-session.jsonl"), "utf8")).toBe(
			formatRecording(buildKrakenDemo(7)),
		);
	});

	it("is deterministic for a seed and labelled synthetic", () => {
		const a = buildDemoSession(7);
		expect(JSON.stringify(buildDemoSession(7))).toBe(JSON.stringify(a));
		expect(a[0]).toMatchObject({
			t: 0,
			kind: "meta",
			synthetic: true,
			description: "SYNTHETIC DEMO generated by scripts/make-demo.ts",
		});
		expect(a.some((line) => line.kind === "globals")).toBe(true);
		expect(Math.max(...a.map((line) => line.t))).toBeLessThanOrEqual(200_000);
	});

	it("fast-forwards the whole engine at speed 4, so the same trades close", async () => {
		const reasons = async (speed: number) =>
			ofType((await runDemo(speed)).events, "close").map((event) => `${event.trade.symbol}:${event.trade.reason}`);
		const atFour = await reasons(4);
		expect(atFour).toHaveLength(8);
		expect(atFour).toEqual(await reasons(1));
	});

	it("plays every scripted beat through the real trading core", async () => {
		const { events, symbols } = await runDemo();
		const sym = (mint: string) => symbols.get(mint) ?? mint;

		const closes = ofType(events, "close").map((event) => event.trade);
		expect(closes.map((trade) => `${trade.symbol}:${trade.reason}`)).toEqual([
			"ALPHA:take_profit",
			"BETA:take_profit",
			"GAMMA:take_profit",
			"DELTA:take_profit",
			"EPSILON:take_profit",
			"ZETA:stop_loss",
			"THETA:stop_loss",
			"IOTA:stop_loss",
		]);

		const failed = ofType(events, "order").filter((event) => event.order.status === "failed");
		expect(failed.map((event) => [event.order.symbol, event.order.error])).toEqual([
			["ETA", "Coin migrated before fill"],
		]);

		const rejections = new Map<string, string>();
		for (const { check } of ofType(events, "check")) {
			const first = check.results.find((result) => !result.pass);
			if (check.verdict === "rejected" && first && !rejections.has(sym(check.mint)))
				rejections.set(sym(check.mint), first.rule);
		}
		expect(rejections.get("RUGPULL")).toBe("blocklist");
		expect(rejections.get("SPAMC")).toBe("serial_launcher");
		expect(rejections.get("MAYHEM")).toBe("not_mayhem");
		expect(rejections.get("KAPPA")).toBe("min_real_sol");

		const tiers = new Set<TierId>();
		const seen: ClosedTrade[] = [];
		for (const trade of closes) {
			seen.push(trade);
			tiers.add(activeTier(seen, trade.closedAt + 1));
		}
		for (const tier of ["ice", "neon", "gold", "fever", "cold"] as const) expect(tiers.has(tier)).toBe(true);

		expect(ofType(events, "feed").some((event) => event.status === "down")).toBe(true);

		const iotaClose = closes.find((trade) => trade.symbol === "IOTA");
		const riskAfterIota = ofType(events, "risk").filter((event) => event.risk.tiltUntil !== null);
		expect(iotaClose).toBeDefined();
		expect(riskAfterIota.length).toBeGreaterThan(0);

		const kappaChecks = ofType(events, "check").filter((event) => sym(event.check.mint) === "KAPPA");
		expect(kappaChecks.at(-1)?.check).toMatchObject({ verdict: "approved", attempt: 2 });
		const kappaMint = kappaChecks[0].check.mint;
		expect(ofType(events, "order").some((event) => event.order.mint === kappaMint)).toBe(false);
		expect(
			ofType(events, "log").some((event) => event.line.message.startsWith("Skipped KAPPA: Tilt cooldown until")),
		).toBe(true);

		let open = 0;
		let peak = 0;
		for (const event of events) {
			if (event.type === "order" && event.order.side === "buy" && event.order.status === "filled") open += 1;
			if (event.type === "close") open -= 1;
			peak = Math.max(peak, open);
		}
		expect(peak).toBeLessThanOrEqual(3);
		expect(open).toBe(0);
	});
});
