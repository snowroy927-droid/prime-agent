function holderLine(random: () => number, kind: "healthy" | "thin"): HolderSummary {
	const count = kind === "healthy" ? 14 : 6;
	const holders = Array.from({ length: count }, (_, i) => {
		const basisPoints = BigInt(Math.round(120 - i * 6 + random() * 10));
		return { account: keyFrom(random).toBase58(), amount: (SUPPLY * basisPoints) / 10_000n };
	});
	return { supply: SUPPLY, curveAccount: keyFrom(random).toBase58(), holders };
}

export function buildDemoSession(seed: number): RecordingLine[] {
	const random = mulberry32(seed);
	const global = syntheticGlobal();
	const globals: Globals = { global, feeConfig: null };
	const spamCreator = keyFrom(random);
	const lines: RecordingLine[] = [
		{ t: 0, kind: "meta", synthetic: true, description: DEMO_DESCRIPTION, createdAt: DEMO_CREATED_AT },
		{ t: 0, kind: "globals", globals: toJsonSafe(globals) },
		{ t: 0, kind: "feed", status: "live" },
		{ t: 95_000, kind: "feed", status: "down" },
		{ t: 105_000, kind: "feed", status: "live" },
	];

	for (const coin of SCRIPT) {
		const mint = keyFrom(random);
		const creator = coin.spamCreator ? spamCreator : keyFrom(random);
		const fresh: BondingCurve = { ...pump.newBondingCurve(global), creator, isMayhemMode: coin.mayhem === true };
		const launchQuote = fresh.virtualQuoteReserves.add(sol(coin.realSol));
		const start = Math.round(coin.at * 1_000);
		const launchCurve = curveAt(fresh, launchQuote);

		lines.push({
			t: start,
			kind: "launch",
			raw: JSON.stringify({
				signature: `synthetic-${coin.symbol.toLowerCase()}`,
				mint: mint.toBase58(),
				traderPublicKey: creator.toBase58(),
				txType: "create",
				name: coin.name,
				symbol: coin.symbol,
				uri: null,
				marketCapSol: Number(curveMarketCapSol(launchCurve).toFixed(4)),
			}),
		});
		lines.push({
			t: start,
			kind: "holders",
			mint: mint.toBase58(),
			holders: toJsonSafe(holderLine(random, coin.holders)),
		});

		coin.path.forEach((multiple, second) => {
			const t = start + second * 1_000;
			if (coin.completeAtMs !== undefined && t - start > coin.completeAtMs) return;
			const jitter = second === 0 ? 1 : 1 + (random() - 0.5) * 0.01;
			const realSol = coin.realSolFrom && second >= coin.realSolFrom.sec ? coin.realSolFrom.realSol : coin.realSol;
			const baseQuote = fresh.virtualQuoteReserves.add(sol(realSol));
			const target = new BN(Math.round(Number(baseQuote.toString()) * Math.sqrt(multiple * jitter)).toString());
			const snap: CurveSnapshot = {
				mint: mint.toBase58(),
				curve: curveAt(fresh, target),
				tokenProgram: "spl",
				slot: 0,
				at: 0,
			};
			lines.push({ t, kind: "curve", mint: mint.toBase58(), snap: toJsonSafe(snap) });
		});

		if (coin.completeAtMs !== undefined) {
			const done: CurveSnapshot = {
				mint: mint.toBase58(),
				curve: { ...curveAt(fresh, launchQuote), complete: true },
				tokenProgram: "spl",
				slot: 0,
				at: 0,
			};
			lines.push({ t: start + coin.completeAtMs, kind: "curve", mint: mint.toBase58(), snap: toJsonSafe(done) });
		}
	}

	return lines.sort((a, b) => a.t - b.t);
}
