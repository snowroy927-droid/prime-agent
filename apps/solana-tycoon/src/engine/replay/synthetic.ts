function keyFrom(random: () => number): PublicKey {
	const seed = new Uint8Array(32);
	for (let i = 0; i < seed.length; i++) seed[i] = Math.floor(random() * 256);
	return web3.Keypair.fromSeed(seed).publicKey;
}

// Pump's Global account with mainnet launch parameters, decoded from a zeroed account so every
// field the SDK reads exists. feeConfig stays null, so quotes use the Global fee fields.
export function syntheticGlobal(): Global {
	const discriminator = createHash("sha256").update("account:Global").digest().subarray(0, 8);
	const zeroed = pump.PUMP_SDK.decodeGlobal({
		data: Buffer.concat([discriminator, Buffer.alloc(pump.GLOBAL_SIZE)]),
		owner: pump.PUMP_PROGRAM_ID,
		executable: false,
		lamports: 0,
		rentEpoch: 0,
	});
	return {
		...zeroed,
		initialized: true,
		initialVirtualTokenReserves: new BN("1073000000000000"),
		initialVirtualSolReserves: new BN("30000000000"),
		initialRealTokenReserves: new BN("793100000000000"),
		tokenTotalSupply: new BN(SUPPLY.toString()),
		feeBasisPoints: new BN(95),
		creatorFeeBasisPoints: new BN(5),
		initialVirtualQuoteReserves: new BN("30000000000"),
	};
}

// Moves a fresh curve to a given virtual SOL reserve as if buys and sells had traded against it.
function curveAt(fresh: BondingCurve, virtualQuote: BN): BondingCurve {
	const k = fresh.virtualQuoteReserves.mul(fresh.virtualTokenReserves);
	const virtualToken = k.div(virtualQuote);
	return {
		...fresh,
		virtualQuoteReserves: virtualQuote,
		virtualTokenReserves: virtualToken,
		realQuoteReserves: virtualQuote.sub(fresh.virtualQuoteReserves),
		realTokenReserves: fresh.realTokenReserves.sub(fresh.virtualTokenReserves.sub(virtualToken)),
	};
}

const sol = (amount: number): BN => new BN(Math.round(amount * LAMPORTS).toString());

