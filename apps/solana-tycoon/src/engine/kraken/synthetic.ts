export const KRAKEN_DEMO_DESCRIPTION = "SYNTHETIC DEMO (Kraken) generated by scripts/make-demo.ts";
const CREATED_AT = "2026-10-15T00:00:00.000Z";
const EPOCH = Date.parse(CREATED_AT);
const MINUTE_MS = 60_000;
const TICK_MS = 2_000;
const END_MS = 200_000;
const OUTAGE = { from: 100_000, to: 108_000 };
const DELIST_MS = 120_000;
const HISTORY_MIN = 60;

interface PairScript {
	symbol: string;
	base: number;
	priceDecimals: number;
	ordermin: string;
	spreadPct: number;
	volume24h: number;
	// Base units traded per minute in the quiet part of the history; the last 14 minutes trade ten times that.
	minuteVolume: number;
	// [second, price multiple of base]; each multiple holds until the next keyframe.
	path: readonly (readonly [number, number])[] | "sol";
	ticksUntil?: number;
}

