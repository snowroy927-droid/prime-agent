const key = (pair: PairScript) => `${pair.symbol}USD`;
const wsname = (pair: PairScript) => `${pair.symbol}/USD`;
const round = (value: number, decimals: number) => Number(value.toFixed(decimals));
const krakenTime = (ms: number) => new Date(ms).toISOString().replace(/\.(\d{3})Z$/, ".$1000000Z");

function multipleAt(path: readonly (readonly [number, number])[], second: number): number {
	let multiple = path[0][1];
	for (const [at, value] of path) if (at <= second) multiple = value;
	return multiple;
}

function historyMultiple(pair: PairScript, minutesAgo: number): number {
	if (pair.path === "sol" || minutesAgo >= 15) return 1;
	return 1 + (15 - minutesAgo) * 0.0014;
}

function assetPairs(pairs: readonly PairScript[]): Record<string, unknown> {
	return Object.fromEntries(
		pairs.map((pair) => [
			key(pair),
			{
				altname: key(pair),
				wsname: wsname(pair),
				base: pair.symbol,
				quote: "ZUSD",
				pair_decimals: pair.priceDecimals,
				lot_decimals: 2,
				ordermin: pair.ordermin,
				costmin: "0.5",
				status: "online",
			},
		]),
	);
}

// A seeded Kraken session for `npm run demo`: every price is synthetic, including SOL/USD, and none is a quote.
export function buildKrakenDemo(seed: number): RecordingLine[] {
	const random = mulberry32(seed);
	const jitter = (value: number, pct: number) => value * (1 + (random() - 0.5) * 2 * pct);
	const lines: RecordingLine[] = [
		{ t: 0, kind: "meta", synthetic: true, description: KRAKEN_DEMO_DESCRIPTION, createdAt: CREATED_AT },
		{ t: 0, kind: "kraken_rest", endpoint: "AssetPairs", query: "", body: assetPairs(SCRIPT) },
	];

	for (const pair of SCRIPT) {
		const rows = Array.from({ length: HISTORY_MIN }, (_, i) => {
			const minutesAgo = HISTORY_MIN - i;
			const close = round(pair.base * jitter(historyMultiple(pair, minutesAgo), 0.0002), pair.priceDecimals);
			const volume = jitter(pair.minuteVolume * (minutesAgo < 15 ? 10 : 1), 0.1).toFixed(2);
			const text = close.toFixed(pair.priceDecimals);
			return [(EPOCH - minutesAgo * MINUTE_MS) / 1000, text, text, text, text, text, volume, 25];
		});
		lines.push({
			t: 0,
			kind: "kraken_rest",
			endpoint: "OHLC",
			query: key(pair),
			body: { [key(pair)]: rows, last: (EPOCH - MINUTE_MS) / 1000 },
		});
	}

	lines.push(
		{ t: 0, kind: "kraken_feed", status: "live" },
		{ t: OUTAGE.from, kind: "kraken_feed", status: "down" },
		{ t: OUTAGE.to, kind: "kraken_feed", status: "live" },
		{
			t: DELIST_MS,
			kind: "kraken_rest",
			endpoint: "AssetPairs",
			query: "",
			body: assetPairs(SCRIPT.filter((pair) => pair.symbol !== "HALTY")),
		},
	);

	const minuteVolume = new Map<string, { begin: number; volume: number }>();
	for (let t = 0; t <= END_MS; t += TICK_MS) {
		if (t >= OUTAGE.from && t < OUTAGE.to) continue;
		for (const pair of SCRIPT) {
			if (pair.ticksUntil !== undefined && t >= pair.ticksUntil) continue;
			const multiple = pair.path === "sol" ? jitter(1, 0.002) : multipleAt(pair.path, t / 1000);
			const price = pair.base * multiple;
			const half = pair.spreadPct / 200;
			lines.push({
				t,
				kind: "kraken_ws",
				raw: JSON.stringify({
					channel: "ticker",
					type: "update",
					data: [
						{
							symbol: wsname(pair),
							bid: round(price * (1 - half), pair.priceDecimals),
							ask: round(price * (1 + half), pair.priceDecimals),
							last: round(price, pair.priceDecimals),
							volume: round(jitter(pair.volume24h, 0.01), 2),
							vwap: round(pair.base * 1.01, pair.priceDecimals),
						},
					],
				}),
			});

			const begin = EPOCH + Math.floor(t / MINUTE_MS) * MINUTE_MS;
			const previous = minuteVolume.get(pair.symbol);
			const traded = jitter((pair.minuteVolume * 10 * TICK_MS) / MINUTE_MS, 0.2);
			const volume = previous && previous.begin === begin ? previous.volume + traded : traded;
			minuteVolume.set(pair.symbol, { begin, volume });
			const close = round(price, pair.priceDecimals);
			lines.push({
				t,
				kind: "kraken_ws",
				raw: JSON.stringify({
					channel: "ohlc",
					type: "update",
					data: [
						{
							symbol: wsname(pair),
							open: close,
							high: close,
							low: close,
							close,
							volume: round(volume, 2),
							interval_begin: krakenTime(begin),
							interval: 1,
						},
					],
				}),
			});
		}
	}

	return lines.sort((a, b) => a.t - b.t);
}
