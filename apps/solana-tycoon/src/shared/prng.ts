// Seeded pseudo-random numbers in [0, 1): the same seed always gives the same sequence. Used for the synthetic
// demo and for cosmetic jitter (shake, particles, noise) so nothing on screen depends on unseeded randomness.
export function mulberry32(seed: number): () => number {
	let state = seed >>> 0;
	return () => {
		state = (state + 0x6d2b79f5) >>> 0;
		let value = state;
		value = Math.imul(value ^ (value >>> 15), value | 1);
		value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
		return ((value ^ (value >>> 14)) >>> 0) / 4_294_967_296;
	};
}
